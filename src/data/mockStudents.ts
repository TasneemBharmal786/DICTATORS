import { Student } from '@/types/student';
import {
  calculateSuccessScore,
  determineRiskAnalysis,
  determineCohort,
  generateXaiDrivers,
  generatePrescriptiveActions,
} from '@/lib/scoringEngine';

function createStudent(data: Omit<Student, 'successScore' | 'risk' | 'cohort' | 'xaiDrivers' | 'actionableInsights'>): Student {
  const successScore = calculateSuccessScore({
    academic: data.academic,
    attendance: data.attendance,
    lms: data.lms,
    engagement: data.engagement,
    placement: data.placement,
    skills: data.skills,
    feedback: data.feedback,
  });

  const risk = determineRiskAnalysis({
    academic: data.academic,
    attendance: data.attendance,
    lms: data.lms,
    placement: data.placement,
    successScore: successScore.overall,
  });

  const cohort = determineCohort({
    academic: data.academic,
    attendance: data.attendance,
    lms: data.lms,
    placement: data.placement,
    engagement: data.engagement,
    successScore: successScore.overall,
    risk,
  });

  const xaiDrivers = generateXaiDrivers({
    academic: data.academic,
    attendance: data.attendance,
    lms: data.lms,
    placement: data.placement,
    engagement: data.engagement,
    skills: data.skills,
  });

  const actionableInsights = generatePrescriptiveActions({
    academic: data.academic,
    attendance: data.attendance,
    lms: data.lms,
    placement: data.placement,
    risk,
  });

  return {
    ...data,
    successScore,
    risk,
    cohort,
    xaiDrivers,
    actionableInsights,
  };
}

